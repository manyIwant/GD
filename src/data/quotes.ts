// 按字符串种子稳定选取一句（同一张明信片每次显示一致）
export function pickQuote(seed: string): string {
  let h = 0;
  for (let i = 0; i < seed.length; i++) {
    h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return STAR_QUOTES[h % STAR_QUOTES.length];
}

